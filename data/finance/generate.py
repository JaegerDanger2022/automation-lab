"""Builds the Ask Finance dataset: two years of sales, invoices and payments for
Northwind Ghana Ltd, a fictional distributor. Writes erp_seed.sql in this folder.

The data has the problems real ERP data has, on purpose:
  * voided invoices (sts = 'V') and soft-deleted rows (del_flg = 1) that must be excluded
  * invoices in USD with a rate to GHS, so totals need converting
  * a fiscal year starting 1 July
  * the same business entered twice under slightly different names
  * part payments and inactive customers
Seeded, so the output is identical every run. Data is "as of" 15 October 2026.
Run: python data/finance/generate.py
"""
from __future__ import annotations

import random
from datetime import date, timedelta
from decimal import Decimal, ROUND_HALF_UP
from pathlib import Path

OUT = Path(__file__).parent / "erp_seed.sql"
AS_OF = date(2026, 10, 15)
START = date(2024, 7, 1)
rng = random.Random(11)
TWO = Decimal("0.01")


def d(x) -> Decimal:
    return Decimal(str(x)).quantize(TWO, ROUND_HALF_UP)


BRANCHES = [("ACC", "Accra Central", "Greater Accra"), ("TML", "Tema Industrial", "Greater Accra"),
            ("KSI", "Kumasi Adum", "Ashanti"), ("TKD", "Takoradi Harbour", "Western")]
REPS = [("R01", "Akosua Boateng", "ACC"), ("R02", "Kwame Asante", "ACC"), ("R03", "Yaw Darko", "TML"),
        ("R04", "Efua Mensah", "TML"), ("R05", "Kofi Owusu", "KSI"), ("R06", "Ama Serwaa", "KSI"),
        ("R07", "Kojo Annan", "TKD"), ("R08", "Abena Quaye", "TKD", "N")]
CATS = [("BEV", "Beverages"), ("GRN", "Grains and flour"), ("OIL", "Cooking oil"), ("CLN", "Cleaning products"),
        ("PKG", "Packaging"), ("PER", "Personal care")]
ITEMS = [
    ("BEV-001", "Bottled water 500ml x24", "BEV", "CTN", 38), ("BEV-002", "Malt drink 330ml x24", "BEV", "CTN", 96),
    ("BEV-003", "Orange juice 1L x12", "BEV", "CTN", 140), ("BEV-004", "Energy drink 250ml x24", "BEV", "CTN", 155),
    ("GRN-001", "Rice 25kg", "GRN", "BAG", 410), ("GRN-002", "Rice 5kg", "GRN", "BAG", 92),
    ("GRN-003", "Wheat flour 50kg", "GRN", "BAG", 520), ("GRN-004", "Maize 50kg", "GRN", "BAG", 330),
    ("GRN-005", "Spaghetti 500g x20", "GRN", "CTN", 118), ("OIL-001", "Vegetable oil 5L", "OIL", "GAL", 128),
    ("OIL-002", "Vegetable oil 25L", "OIL", "GAL", 590), ("OIL-003", "Palm oil 4L", "OIL", "GAL", 96),
    ("CLN-001", "Laundry soap bar x40", "CLN", "CTN", 175), ("CLN-002", "Detergent powder 5kg", "CLN", "BAG", 84),
    ("CLN-003", "Bleach 1L x12", "CLN", "CTN", 72), ("CLN-004", "Dishwashing liquid 1L x12", "CLN", "CTN", 98),
    ("PKG-001", "Carrier bags x1000", "PKG", "BDL", 210), ("PKG-002", "Takeaway packs x500", "PKG", "BDL", 260),
    ("PKG-003", "Shrink wrap roll", "PKG", "ROL", 145), ("PER-001", "Toothpaste 100ml x48", "PER", "CTN", 230),
    ("PER-002", "Body lotion 400ml x24", "PER", "CTN", 410), ("PER-003", "Sanitary pads x48", "PER", "CTN", 300),
    ("PER-004", "Tissue roll x48", "PER", "BDL", 165),
]
MARKUP = {"BEV": 1.22, "GRN": 1.12, "OIL": 1.15, "CLN": 1.30, "PKG": 1.35, "PER": 1.40}
SEGS = [("RT", 0.55), ("WS", 0.30), ("GV", 0.08), ("NG", 0.07)]
TERMS = {"RT": 14, "WS": 30, "GV": 60, "NG": 45}
FIRST = ["Kofi", "Ama", "Kwame", "Akua", "Yaw", "Abena", "Kojo", "Efua", "Kwesi", "Adwoa", "Nana", "Esi", "Fiifi", "Afia"]
LAST = ["Mensah", "Owusu", "Boateng", "Asante", "Osei", "Agyeman", "Darko", "Appiah", "Addo", "Ofori", "Quaye", "Tetteh"]
BIZ = ["Enterprise", "Ventures", "Trading", "Stores", "Supermarket", "Wholesale", "Mini Mart", "Provisions"]
INSTITUTIONS = ["Ghana Health Service, {}", "Ministry of Education, {} Office", "{} Municipal Assembly",
                "{} Senior High School", "Ghana Prisons Service, {}", "{} District Hospital"]
NGOS = ["Hope for Children {}", "Clean Water Initiative {}", "Women in Trade Network {}", "Youth Skills Foundation {}"]
TOWNS = {"ACC": ["Accra", "Madina", "Kaneshie", "Osu"], "TML": ["Tema", "Ashaiman", "Community 25", "Kpone"],
         "KSI": ["Kumasi", "Ejisu", "Obuasi", "Suame"], "TKD": ["Takoradi", "Sekondi", "Tarkwa", "Shama"]}


def usd_rate(day: date) -> Decimal:
    """GHS per USD, drifting month to month."""
    months = (day.year - 2024) * 12 + day.month - 7
    base = 14.8 - 0.12 * months + 0.35 * ((months * 7) % 5 - 2) / 2
    return Decimal(str(round(base, 4)))


def season(day: date) -> float:
    return {12: 1.45, 11: 1.15, 1: 0.8, 3: 1.1, 4: 1.05, 7: 0.9, 8: 0.85}.get(day.month, 1.0)


def main():
    sql: list[str] = ["-- Generated by data/finance/generate.py. Fictional data, as of 2026-10-15.", "BEGIN;",
                      "TRUNCATE erp.aralloc, erp.arpmt, erp.arinvln, erp.arinv, erp.itmmst, erp.catmst, "
                      "erp.custmst, erp.slsrep, erp.brnch CASCADE;"]
    q = lambda s: "NULL" if s is None else "'" + str(s).replace("'", "''") + "'"

    def insert(table, cols, rows, chunk=500):
        for i in range(0, len(rows), chunk):
            vals = ",\n".join("(" + ",".join(r) + ")" for r in rows[i:i + chunk])
            sql.append(f"INSERT INTO erp.{table} ({','.join(cols)}) VALUES\n{vals};")

    insert("brnch", ["br_cd", "br_nm", "rgn"], [[q(a), q(b), q(c)] for a, b, c in BRANCHES])
    insert("slsrep", ["rep_cd", "rep_nm", "br_cd", "actv"],
           [[q(r[0]), q(r[1]), q(r[2]), q(r[3] if len(r) > 3 else "Y")] for r in REPS])
    insert("catmst", ["cat_cd", "cat_desc"], [[q(a), q(b)] for a, b in CATS])
    insert("itmmst", ["itm_cd", "itm_desc", "cat_cd", "uom", "std_cost"],
           [[q(a), q(b), q(c), q(u), str(d(cost))] for a, b, c, u, cost in ITEMS])

    # Customers
    reps_by_br = {}
    for r in REPS:
        reps_by_br.setdefault(r[2], []).append(r[0])
    customers = []
    used = set()
    for n in range(1, 241):
        br = rng.choices(["ACC", "TML", "KSI", "TKD"], weights=[38, 22, 27, 13])[0]
        seg = rng.choices([s for s, _ in SEGS], weights=[w for _, w in SEGS])[0]
        town = rng.choice(TOWNS[br])
        while True:
            if seg == "GV":
                name = rng.choice(INSTITUTIONS).format(town)
            elif seg == "NG":
                name = rng.choice(NGOS).format(town)
            else:
                name = f"{rng.choice(FIRST)} {rng.choice(LAST)} {rng.choice(BIZ)}"
            if name not in used:
                used.add(name)
                break
        limit = {"RT": rng.choice([5000, 10000, 20000]), "WS": rng.choice([50000, 100000, 150000]),
                 "GV": rng.choice([200000, 300000]), "NG": rng.choice([60000, 100000])}[seg]
        crt = START - timedelta(days=rng.randint(0, 900)) if n <= 170 else START + timedelta(days=rng.randint(0, 760))
        customers.append({"cd": f"C{n:05d}", "nm": name, "seg": seg, "br": br, "rep": rng.choice(reps_by_br[br]),
                          "lmt": limit, "actv": "Y", "crt": crt, "weight": rng.lognormvariate(0, 0.9)})
    # The same business entered twice, the second spelling slightly different.
    dup_variants = []
    for c in rng.sample([c for c in customers if c["seg"] in ("RT", "WS")], 6):
        variant = c["nm"].upper().replace("ENTERPRISE", "ENT.").replace("VENTURES", "VENT.").replace(" STORES", " STORE")
        if variant == c["nm"].upper():
            variant = variant + " LTD"
        n = len(customers) + 1
        dup = dict(c, cd=f"C{n:05d}", nm=variant, crt=c["crt"] + timedelta(days=200), weight=c["weight"] * 0.4)
        customers.append(dup)
        dup_variants.append((c["cd"], dup["cd"]))
    for c in rng.sample(customers[:170], 18):
        c["actv"] = "N"
        c["stop"] = START + timedelta(days=rng.randint(60, 600))
    insert("custmst", ["cust_cd", "cust_nm", "seg_cd", "br_cd", "rep_cd", "crdt_lmt", "actv_flg", "crt_dt"],
           [[q(c["cd"]), q(c["nm"]), q(c["seg"]), q(c["br"]), q(c["rep"]), str(d(c["lmt"])), q(c["actv"]), q(c["crt"])]
            for c in customers])

    # Invoices, lines, payments
    inv_rows, line_rows, pmt_rows, alloc_rows = [], [], [], []
    seq = {b[0]: 0 for b in BRANCHES}
    pmt_seq = 0
    weights = [c["weight"] for c in customers]
    day = START
    open_items: list[dict] = []
    while day <= AS_OF:
        if day.weekday() < 6:
            growth = 1 + 0.18 * ((day - START).days / 365)
            n_inv = max(0, int(rng.gauss(7.5 * season(day) * growth, 2.2)))
            for _ in range(n_inv):
                c = rng.choices(customers, weights=weights)[0]
                if c["crt"] > day or ("stop" in c and day > c["stop"]):
                    continue
                br = c["br"] if rng.random() > 0.06 else rng.choice(["ACC", "TML", "KSI", "TKD"])
                seq[br] += 1
                inv_no = f"{br}-{day.strftime('%y')}-{seq[br]:06d}"
                usd = (c["seg"] in ("GV", "NG") and rng.random() < 0.55) or (c["seg"] == "WS" and rng.random() < 0.12)
                cur, fx = ("USD", usd_rate(day)) if usd else ("GHS", Decimal("1"))
                net = Decimal("0")
                n_lines = rng.randint(1, 5) if c["seg"] != "RT" else rng.randint(1, 3)
                for ln, it in enumerate(rng.sample(ITEMS, n_lines), start=1):
                    qty = {"RT": rng.randint(1, 12), "WS": rng.randint(10, 120), "GV": rng.randint(20, 200),
                           "NG": rng.randint(10, 80)}[c["seg"]]
                    price_ghs = Decimal(str(it[4])) * Decimal(str(MARKUP[it[2]])) * Decimal(str(1 + 0.08 * (day - START).days / 365))
                    price = d(price_ghs / fx)
                    disc = Decimal(rng.choice([0, 0, 0, 2.5, 5])) if c["seg"] in ("WS", "GV") else Decimal(0)
                    amt = d(qty * price * (1 - disc / 100))
                    net += amt
                    line_rows.append([q(inv_no), str(ln), q(it[0]), str(d(qty)), str(price), str(d(disc))])
                tax = d(net * Decimal("0.20")) if c["seg"] != "NG" else Decimal("0.00")
                due = day + timedelta(days=TERMS[c["seg"]])
                inv = {"no": inv_no, "cust": c["cd"], "seg": c["seg"], "dt": day, "due": due, "cur": cur, "fx": fx,
                       "total": net + tax, "paid": Decimal("0"), "sts": "O", "del": 0}
                r = rng.random()
                if r < 0.03:
                    inv["sts"] = "V"
                elif r < 0.04:
                    inv["del"] = 1
                inv_rows.append(inv)
                inv["net"], inv["tax"] = net, tax
                if inv["sts"] == "O" and inv["del"] == 0:
                    open_items.append(inv)
        # Payments arriving today
        still = []
        for inv in open_items:
            late = {"RT": 6, "WS": 18, "GV": 55, "NG": 25}[inv["seg"]]
            pay_day = inv["due"] + timedelta(days=int(rng.gauss(late, late / 2 + 3)))
            inv.setdefault("pay_day", pay_day)
            inv.setdefault("never", rng.random() < 0.035)
            if inv["never"] or inv["pay_day"] > day or inv["pay_day"] > AS_OF:
                still.append(inv)
                continue
            # Part payment sometimes, then the rest later
            if rng.random() < 0.15 and inv["paid"] == 0:
                part = d(inv["total"] * Decimal(rng.choice(["0.3", "0.5", "0.6"])))
            else:
                part = inv["total"] - inv["paid"]
            pmt_seq += 1
            pid = f"P{pmt_seq:06d}"
            mthd = rng.choices(["MOMO", "BANK", "CHQ", "CASH"], weights=[40, 35, 10, 15])[0]
            ref = {"MOMO": f"MP{rng.randint(10**9, 10**10 - 1)}", "BANK": f"TRF/{inv['no']}",
                   "CHQ": f"CHQ {rng.randint(100000, 999999)}", "CASH": None}[mthd]
            pmt_rows.append([q(pid), q(inv["cust"]), q(day), q(inv["cur"]),
                             str(inv["fx"] if inv["cur"] == "GHS" else usd_rate(day)), str(part), q(mthd), q(ref)])
            alloc_rows.append([q(pid), q(inv["no"]), str(part)])
            inv["paid"] += part
            if inv["paid"] >= inv["total"]:
                inv["sts"] = "P"
            else:
                inv["pay_day"] = day + timedelta(days=rng.randint(10, 40))
                still.append(inv)
        open_items = still
        day += timedelta(days=1)

    insert("arinv", ["inv_no", "cust_cd", "br_cd", "inv_dt", "due_dt", "curr_cd", "fx_rt", "net_amt", "tax_amt", "sts", "del_flg"],
           [[q(i["no"]), q(i["cust"]), q(i["no"][:3]), q(i["dt"]), q(i["due"]), q(i["cur"]), str(i["fx"]), str(i["net"]),
             str(i["tax"]), q(i["sts"]), str(i["del"])] for i in inv_rows])
    insert("arinvln", ["inv_no", "ln_no", "itm_cd", "qty", "unit_prc", "disc_pct"], line_rows)
    insert("arpmt", ["pmt_id", "cust_cd", "pmt_dt", "curr_cd", "fx_rt", "amt", "mthd", "ref"], pmt_rows)
    insert("aralloc", ["pmt_id", "inv_no", "alloc_amt"], alloc_rows)
    sql.append("COMMIT;")
    OUT.write_text("\n".join(sql) + "\n")
    print(f"{len(customers)} customers ({len(dup_variants)} duplicates), {len(inv_rows)} invoices, "
          f"{len(line_rows)} lines, {len(pmt_rows)} payments. Duplicates: {dup_variants}")


if __name__ == "__main__":
    main()
